#include "libft.h"

int	ft_memcmp(const void *s1, const void *s2, size_t n)
{
	unsigned char	*p1;
	unsigned char	*p2;
	size_t			index;

	p1 = (unsigned char *)s1;
	p2 = (unsigned char *)s2;
	index = 0;
	while (index < n)
	{
		if (p1[index] != p2[index])
			return (p1[index] - p2[index]);
		index++;
	}
	return (0);
}
